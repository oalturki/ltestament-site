/* «المصحف ككتاب» — an open book that the reader pages through.
   The Arabic page is the Madinah Mushaf exactly as printed by the King Fahd Complex (1421H print, KFGQPC V2):
   15 lines per page, each line breaking where it breaks in print, drawn with the Complex's per-page fonts
   (fonts/qpc-v2/p<N>.woff2) from data/mushaf/p<N>.json — both built by tools/build_mushaf.py from QUL data.
   Two modes:
   - "bilingual": right-hand page = Mushaf text, left-hand page = the meaning of the same verses (QuranEnc.com).
   - "mushaf":    two Mushaf pages side by side, as a printed Mushaf opens (page 1 on the right, 2 on the left).
   Used two ways:
   - the full page /book/ (window.BOOK config, <body class="bk">): index, page number, slider, keyboard, remembers the page;
   - embedded in a home page (<section data-book='{config}'>): starts at Al-Fatiha, loads only when scrolled near.
   Elements are found by data-bk="..." inside each root. Config is generated by tools/build_book.py. */
(function () {
  'use strict';
  var QE = 'https://quranenc.com/api/v1/translation/sura/';
  var TOTAL = 604;
  var AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
  var MAP_P = null;                       // Mushaf page map, one request per page view
  var trCache = {};                       // key|surah -> verses, shared by every book on the page
  var BASE = window.LT_ASSET_BASE || '';  // where /fonts and /data live (overridable for previews)
  var fontCache = {}, mCache = {};        // page fonts and page data, shared by every book on the page

  function arNum(n) { return String(n).replace(/[0-9]/g, function (d) { return AR_DIGITS[d]; }); }
  function esc(t) { return String(t == null ? '' : t).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  function fnMarks(t) { return esc(t).replace(/\[(\d+)\]/g, '<sup>$1</sup>'); }
  function store(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  function load(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function track(ev, d) { try { if (window.ltTrack) window.ltTrack(ev, d); } catch (e) {} }
  var wait = function (ms) { return new Promise(function (r) { setTimeout(r, ms); }); };
  function getJSON(url, ms) {
    var ctl = new AbortController(), timer = setTimeout(function () { ctl.abort(); }, ms || 15000);
    return fetch(url, { signal: ctl.signal }).then(function (r) {
      clearTimeout(timer);
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return r.json();
    }).finally(function () { clearTimeout(timer); });
  }
  function getMap(url) {
    if (!MAP_P) { MAP_P = getJSON(url || '/data/quran-pages.json'); MAP_P.catch(function () { MAP_P = null; }); }
    return MAP_P;
  }
  function trSurah(key, s) {
    var id = key + '|' + s;
    if (!trCache[id]) {
      trCache[id] = getJSON(QE + key + '/' + s).then(function (d) {
        return d.result.slice().sort(function (a, b) { return a.aya - b.aya; });
      });
      trCache[id].catch(function () { delete trCache[id]; });
    }
    return trCache[id];
  }
  // The Complex's font for one Mushaf page; every page has its own glyphs, so each page needs its own font.
  function pageFont(p) {
    if (!fontCache[p]) {
      var f = new FontFace('qpc-p' + p, 'url(' + BASE + '/fonts/qpc-v2/p' + p + '.woff2)', { display: 'block' });
      fontCache[p] = f.load().then(function (ff) { document.fonts.add(ff); });
      fontCache[p].catch(function () { delete fontCache[p]; });
    }
    return fontCache[p];
  }
  var headerFont = null;
  function surahHeaderFont() {
    if (!headerFont) {
      headerFont = document.fonts && document.fonts.load ? document.fonts.load("40px 'QPC Surah Header'", '\uFC45') : Promise.resolve();
      headerFont.catch(function () { headerFont = null; });
    }
    return headerFont;
  }
  function mushafPage(p) {
    if (!mCache[p]) {
      mCache[p] = Promise.all([getJSON(BASE + '/data/mushaf/p' + p + '.json'), pageFont(p), pageFont(1), surahHeaderFont()])
        .then(function (r) { return r[0]; });
      mCache[p].catch(function () { delete mCache[p]; });
    }
    return mCache[p];
  }
  function cleanTr(t) { return String(t || '').replace(/^\s*\(?\d+\)?[.\-–]\s*/, ''); }
  function cleanAr(t) { return String(t || '').replace(/ /g, ' ').trim(); }

  function Book(root, C) {
    var U = C.ui, embed = !!C.embed, mushaf = C.mode === 'mushaf';
    var q = function (k) { return root.querySelector('[data-bk="' + k + '"]'); };
    var book = q('book'), pgR = q('pgAr'), pgL = q('pgTr');
    var MAP = null, surahStart = [], cur = 1, busy = false, arCache = {};
    var trKey = pickTranslation();

    function tr() { return C.translations.filter(function (t) { return t.key === trKey; })[0] || C.translations[0]; }
    function pickTranslation() {
      var saved = embed ? null : load('lt_book_tr');
      var ok = saved && C.translations.some(function (t) { return t.key === saved; });
      return ok ? saved : C.defaultTranslation;
    }
    function uiNum(n) { return C.arabicDigits ? arNum(n) : String(n); }
    function narrow() { return window.matchMedia('(max-width:900px)').matches; }
    function step() { return mushaf && !narrow() ? 2 : 1; }
    function norm(p) { p = Math.max(1, Math.min(TOTAL, p | 0)); return step() === 2 && p % 2 === 0 ? p - 1 : p; }

    /* ---------- data ---------- */
    function versesOf(p) {
      var r = MAP.pages[p - 1], out = [];
      for (var s = r[0]; s <= r[2]; s++) {
        var from = s === r[0] ? r[1] : 1, to = s === r[2] ? r[3] : MAP.verses[s - 1];
        for (var v = from; v <= to; v++) out.push([s, v]);
      }
      return out;
    }
    function surahsOf(p) { var r = MAP.pages[p - 1], a = []; for (var s = r[0]; s <= r[2]; s++) a.push(s); return a; }
    function arPage(p) { return mushafPage(p); }
    function pageData(p) {
      var key = trKey, second = mushaf && step() === 2 && p + 1 <= TOTAL;
      return Promise.all([
        arPage(p),
        second ? arPage(p + 1) : null,
        mushaf ? [] : Promise.all(surahsOf(p).map(function (s) { return trSurah(key, s); })),
        mushaf ? null : trSurah(key, 1) // translated basmala
      ]).then(function (r) {
        var trBy = {};
        r[2].forEach(function (l) { l.forEach(function (x) { trBy[x.sura + ':' + x.aya] = x; }); });
        return { ar: r[0], ar2: r[1], tr: trBy, basmala: r[3] && r[3][0] };
      });
    }

    /* ---------- rendering ---------- */
    // Basmala line: the basmala of Al-Fatiha (page 1, words 1–4) in the page-1 font, as the printed Mushaf repeats it.
    var BASMALA = ['ﱁ', 'ﱂ', 'ﱃ', 'ﱄ'];
    function renderAr(el, p, m) {
      var first = MAP.pages[p - 1][0], html = '';
      m.l.forEach(function (L) {
        if (L[0] === 's') html += '<div class="ml ml-s"><span class="mh" role="img" aria-label="سورة ' + esc(C.arabicNames[L[1] - 1]) + '">' + L[2] + '</span></div>';
        else if (L[0] === 'b') html += '<div class="ml ml-c ml-b">' + BASMALA.map(function (g) { return '<span>' + g + '</span>'; }).join('') + '</div>';
        else html += '<div class="ml' + (L[1] ? ' ml-c' : '') + '">' + L[2].map(function (w) {
          return '<span data-l="' + w[1] + '">' + w[0] + '</span>';
        }).join('') + '</div>';
      });
      el.setAttribute('dir', 'rtl'); el.setAttribute('lang', 'ar'); el.style.fontFamily = '';
      el.classList.add('bk-arpage', 'bk-mpage'); el.classList.remove('bk-trpage');
      el.innerHTML =
        '<div class="bk-head"><b>سورة ' + esc(C.arabicNames[first - 1]) + '</b><span>الجزء ' + arNum(MAP.juz[p - 1]) + '</span></div>' +
        '<div class="bk-mushaf' + (p <= 2 ? ' bk-m-open' : '') + '" data-p="' + p + '" style="font-family:\'qpc-p' + p + '\'">' + html + '</div>' +
        '<div class="bk-foot"><span>' + arNum(p) + '</span></div>';
    }
    // Size a Mushaf page: 15 equal lines; the font grows until the longest line fills the width (or the line height is reached).
    function fitMushaf(el) {
      var box = el.querySelector('.bk-mushaf');
      if (!box || el.offsetParent === null) return;
      var open = box.classList.contains('bk-m-open');   // pages 1–2: few lines, set larger in the middle of the page
      var H = box.clientHeight, W = box.clientWidth, lh = H / (open ? 12 : 15), F0 = 20;
      if (!H || !W) return;
      box.style.setProperty('--lh', lh + 'px');
      box.style.removeProperty('--mw');
      box.classList.add('measuring');
      box.style.fontSize = F0 + 'px';
      var maxW = 0;
      box.querySelectorAll('.ml:not(.ml-s):not(.ml-b)').forEach(function (l) { maxW = Math.max(maxW, l.getBoundingClientRect().width); });
      box.classList.remove('measuring');
      var fs = maxW ? F0 * (W * (open ? 0.72 : 0.99)) / maxW : lh / 1.6;
      fs = Math.min(fs, lh / 1.55);
      box.style.fontSize = fs + 'px';
      var lineW = Math.min(W, maxW * fs / F0 / (open ? 1 : 0.99));
      if (!open) box.style.setProperty('--mw', lineW + 'px');
      // The header glyph (frame + surah name) is 3.28em wide and 0.41em tall: as wide as the text, within about one line.
      var headW = open ? W * 0.8 : lineW;
      box.querySelectorAll('.mh').forEach(function (h) { h.style.fontSize = Math.min(headW / 3.28, lh * 1.15 / 0.41) + 'px'; });
      box.classList.add('ready');
    }
    function renderTr(el, p, d) {
      var t = tr(), names = t.names === 'ar' ? C.arabicNames : C.names[t.names], html = '', notes = [];
      var first = MAP.pages[p - 1][0];
      versesOf(p).forEach(function (sv) {
        var s = sv[0], v = sv[1], x = d.tr[s + ':' + v] || {};
        if (v === 1) {
          html += '<div class="bk-surah">' + esc(names[s - 1]) + '</div>';
          if (s !== 1 && s !== 9 && d.basmala) html += '<div class="bk-basmala">' + esc(cleanTr(d.basmala.translation).replace(/\[\d+\]/g, '')) + '</div>';
        }
        html += '<span class="vn">' + v + '</span>' + fnMarks(cleanTr(x.translation)) + ' ';
        if (x.footnotes) notes.push('(' + s + ':' + v + ') ' + x.footnotes);
      });
      el.setAttribute('dir', t.dir); el.setAttribute('lang', t.lang); el.style.fontFamily = t.font;
      el.classList.add('bk-trpage'); el.classList.remove('bk-arpage');
      el.innerHTML =
        '<div class="bk-head"><b>' + esc(names[first - 1]) + '</b><span>' + esc(t.juz) + ' ' + MAP.juz[p - 1] + '</span></div>' +
        '<div class="bk-content">' + html +
          (notes.length ? '<details class="bk-fn"><summary>' + esc(U.notes) + ' (' + notes.length + ')</summary><p>' + fnMarks(notes.join('\n\n')) + '</p></details>' : '') +
          '<p class="bk-credit">' + t.credit + '</p>' +
        '</div>' +
        '<div class="bk-foot"><span>' + p + '</span></div>';
    }
    function renderAll(p, d) {
      renderAr(pgR, p, d.ar);
      if (!mushaf) renderTr(pgL, p, d);
      else if (d.ar2) renderAr(pgL, p + 1, d.ar2);
      else { pgL.innerHTML = ''; pgL.classList.remove('bk-arpage', 'bk-trpage'); }
    }

    // Shrink the text until the page fits; if it still does not fit at the minimum size, let it scroll.
    function fit(page, max, min) {
      var c = page.querySelector('.bk-content');
      if (!c || page.offsetParent === null) return;
      c.classList.remove('scroll');
      var size = max;
      c.style.fontSize = size + 'px';
      while (c.scrollHeight > c.clientHeight + 1 && size > min) { size -= 0.5; c.style.fontSize = size + 'px'; }
      if (c.scrollHeight > c.clientHeight + 1) c.classList.add('scroll');
      c.scrollTop = 0;
    }
    function fitAll() {
      var h = pgR.clientHeight || pgL.clientHeight || 600;
      var trMax = Math.max(14, Math.min(19, h / 34));
      [pgR, pgL].forEach(function (el) {
        if (el.classList.contains('bk-mpage')) fitMushaf(el);
        else if (el.classList.contains('bk-trpage')) fit(el, tr().lang === 'ur' ? trMax + 1 : trMax, 11);
      });
    }
    function showMsg(text, retry) {
      pgR.innerHTML = pgL.innerHTML = '<div class="bk-msg">' + esc(text) + '</div>';
      if (retry) {
        var b = document.createElement('button');
        b.type = 'button'; b.className = 'bk-tab'; b.textContent = U.retry; b.style.marginTop = '12px';
        b.onclick = function () { show(cur, 0); };
        pgL.querySelector('.bk-msg').appendChild(document.createElement('br'));
        pgL.querySelector('.bk-msg').appendChild(b);
      }
    }
    function updateControls() {
      var last = step() === 2 ? Math.min(TOTAL, cur + 1) : cur;
      if (q('pageInput')) q('pageInput').value = cur;
      if (q('range')) q('range').value = cur;
      if (q('rangeLbl')) q('rangeLbl').textContent = U.page + ' ' + uiNum(cur) + (last !== cur ? '–' + uiNum(last) : '') + ' / ' + uiNum(TOTAL);
      q('next').disabled = last >= TOTAL;
      q('prev').disabled = cur <= 1;
      if (q('surahSel')) q('surahSel').value = String(MAP.pages[cur - 1][0]);
      if (!embed) { history.replaceState(null, '', '#p=' + cur); store('lt_book_page', String(cur)); }
    }

    /* ---------- page turning ---------- */
    function instant(fn) { book.classList.remove('anim'); fn(); void book.offsetWidth; book.classList.add('anim'); }
    function show(p, dir) {
      p = norm(p);
      if (busy) return;
      busy = true;
      var slow = setTimeout(function () { book.style.opacity = '0.6'; }, 250);
      pageData(p).then(function (d) {
        clearTimeout(slow); book.style.opacity = '';
        var animate = dir && !window.matchMedia('(prefers-reduced-motion:reduce)').matches;
        if (!animate) { cur = p; renderAll(p, d); fitAll(); updateControls(); busy = false; prefetch(); return; }
        // RTL book: going forward lifts the LEFT page over to the right; going back lifts the RIGHT page.
        var one = narrow(), vis = (mushaf || book.dataset.show !== 'tr') ? pgR : pgL;
        var lift = one ? vis : (dir > 0 ? pgL : pgR), land = one ? vis : (dir > 0 ? pgR : pgL);
        var liftCls = lift === pgL ? 'fold-l' : 'fold-r', landCls = land === pgL ? 'fold-l' : 'fold-r';
        book.classList.add('anim');
        lift.classList.add(liftCls);
        return wait(280).then(function () {
          cur = p;
          instant(function () { renderAll(p, d); lift.classList.remove(liftCls); land.classList.add(landCls); });
          fitAll();
          land.classList.remove(landCls);
          updateControls();
          return wait(290);
        }).then(function () { busy = false; prefetch(); });
      }).catch(function () {
        clearTimeout(slow); book.style.opacity = ''; busy = false;
        showMsg(U.error, true);
      });
    }
    function go(delta) { show(cur + delta * step(), delta); }
    function prefetch() { var n = cur + step(); if (n <= TOTAL) pageData(norm(n)).catch(function () {}); }

    /* ---------- controls ---------- */
    function buildControls() {
      var sel = q('surahSel');
      if (sel) {
        sel.innerHTML = C.uiNames.map(function (n, i) { return '<option value="' + (i + 1) + '">' + uiNum(i + 1) + '. ' + esc(n) + '</option>'; }).join('');
        sel.onchange = function () { show(surahStart[+sel.value - 1], 0); };
      }
      var ts = q('trSel');
      if (ts) {
        ts.innerHTML = C.translations.map(function (t) { return '<option value="' + t.key + '">' + esc(t.label) + '</option>'; }).join('');
        ts.value = trKey;
        ts.onchange = function () {
          trKey = ts.value;
          if (!embed) store('lt_book_tr', trKey);
          var t = tr();
          if (t.fontUrl && !document.querySelector('link[data-font="' + t.key + '"]')) {
            var l = document.createElement('link'); l.rel = 'stylesheet'; l.href = t.fontUrl; l.dataset.font = t.key; document.head.appendChild(l);
          }
          track('book_open', trKey);
          show(cur, 0);
        };
      }
      var pi = q('pageInput');
      if (pi) pi.onchange = function () { show(+pi.value || 1, 0); };
      var rg = q('range');
      if (rg) {
        rg.oninput = function () { q('rangeLbl').textContent = U.page + ' ' + uiNum(rg.value) + ' / ' + uiNum(TOTAL); };
        rg.onchange = function () { show(+rg.value, 0); };
      }
      q('next').onclick = function () { go(1); };
      q('prev').onclick = function () { go(-1); };

      // RTL book: the left arrow moves forward. Full page only, so a home page keeps its own keys.
      if (!embed) document.addEventListener('keydown', function (e) {
        if (e.target && /INPUT|SELECT|TEXTAREA/.test(e.target.tagName)) return;
        if (e.key === 'ArrowLeft' || e.key === 'PageDown') { e.preventDefault(); go(1); }
        if (e.key === 'ArrowRight' || e.key === 'PageUp') { e.preventDefault(); go(-1); }
      });
      // Swipe: finger moving to the right turns forward (as when lifting the left page of an Arabic book).
      var x0 = null, y0 = null;
      book.addEventListener('touchstart', function (e) { x0 = e.touches[0].clientX; y0 = e.touches[0].clientY; }, { passive: true });
      book.addEventListener('touchend', function (e) {
        if (x0 === null) return;
        var dx = e.changedTouches[0].clientX - x0, dy = e.changedTouches[0].clientY - y0;
        x0 = null;
        if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.4) go(dx > 0 ? 1 : -1);
      }, { passive: true });

      // Narrow screens, bilingual book: tabs for text / meaning
      var tabs = root.querySelectorAll('.bk-tab[data-show]');
      function setShow(v) {
        book.dataset.show = v;
        if (!embed) store('lt_book_show', v);
        tabs.forEach(function (b) { b.classList.toggle('on', b.dataset.show === v); });
        requestAnimationFrame(fitAll);
      }
      tabs.forEach(function (b) { b.onclick = function () { setShow(b.dataset.show); }; });
      setShow(mushaf ? 'ar' : ((!embed && load('lt_book_show')) || C.defaultShow));

      var wasStep = step(), rt;
      window.addEventListener('resize', function () {
        clearTimeout(rt);
        rt = setTimeout(function () {
          if (step() !== wasStep) { wasStep = step(); show(cur, 0); } else fitAll();
        }, 150);
      });
    }

    function startPage() {
      if (embed) return 1;
      var m = /[#&]p=(\d+)/.exec(location.hash);
      var p = m ? +m[1] : +(load('lt_book_page') || 1);
      return p >= 1 && p <= TOTAL ? p : 1;
    }

    showMsg(U.loading);
    getMap(C.dataUrl || BASE + '/data/quran-pages.json').then(function (m) {
      MAP = m;
      MAP.pages.forEach(function (r, i) {
        for (var s = r[0]; s <= r[2]; s++) if (!surahStart[s - 1] && (s !== r[0] || r[1] === 1)) surahStart[s - 1] = i + 1;
      });
      buildControls();
      track('book_open', embed ? 'embed' : trKey);
      show(startPage(), 0);
    }).catch(function () { showMsg(U.error, false); });
  }

  /* ---------- start every book on the page ---------- */
  if (window.BOOK && document.body.classList.contains('bk')) Book(document.body, window.BOOK);
  document.querySelectorAll('[data-book]').forEach(function (el) {
    var C;
    try { C = JSON.parse(el.getAttribute('data-book')); } catch (e) { return; }
    C.embed = true;
    var started = false, startIt = function () { if (!started) { started = true; Book(el, C); } };
    if (!('IntersectionObserver' in window)) return startIt();
    var io = new IntersectionObserver(function (es) {
      if (es.some(function (x) { return x.isIntersecting; })) { io.disconnect(); startIt(); }
    }, { rootMargin: '600px 0px' });
    io.observe(el);
  });
})();
