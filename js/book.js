    function nextAyah(s, a) { return a < MAP.verses[s - 1] ? [s, a + 1] : (s < 114 ? [s + 1, 1] : null); }
    function ensureVisible(s, a, tries) {
      var p = pageOf(s, a);
      if (visible().indexOf(p) >= 0) return Promise.resolve(true);
      if ((tries || 0) > 8) return Promise.resolve(false);
      return show(p, p > cur ? 1 : -1, true).then(function (ok) {
        return ok ? true : wait(350).then(function () { return ensureVisible(s, a, (tries || 0) + 1); });
      });
    }
    function wordTimes(r, s, a) {
      var p = pageOf(s, a), id = (r.data || r.id) + '|' + p;
      if (!recPages[id]) { recPages[id] = getJSON(BASE + '/data/rec/' + (r.data || r.id) + '/p' + p + '.json'); recPages[id].catch(function () { delete recPages[id]; }); }
      return recPages[id].then(function (m) { return m[s + ':' + a] || []; });
    }
    function ayahTimes(r, s) {
      if (!recSurahs[r.id]) { recSurahs[r.id] = getJSON(BASE + '/data/rec/' + r.id + '.json'); recSurahs[r.id].catch(function () { delete recSurahs[r.id]; }); }
      return recSurahs[r.id].then(function (m) { return m[String(s)] || []; });
    }

    // highlight: hl = {s, a, w} (w = word number, 0 = whole ayah) or {basmala: true}
    function setHl(h) {
      if (hl && h && hl.s === h.s && hl.a === h.a && hl.w === h.w && hl.basmala === h.basmala) return;
      hl = h; applyHl();
    }
    function applyHl() {
      root.querySelectorAll('.ha, .hl').forEach(function (e) { e.classList.remove('ha', 'hl'); });
      if (!hl) return;
      if (hl.basmala) { root.querySelectorAll('.ml-b').forEach(function (e) { e.classList.add('ha'); }); return; }
      root.querySelectorAll('[data-l^="' + hl.s + ':' + hl.a + ':"], [data-v="' + hl.s + ':' + hl.a + '"]').forEach(function (e) { e.classList.add('ha'); });
      if (hl.w) root.querySelectorAll('[data-l="' + hl.s + ':' + hl.a + ':' + hl.w + '"]').forEach(function (e) { e.classList.add('hl'); });
    }
    function setPlayUI() {
      var b = q('play');
      if (!b) return;
      b.classList.toggle('on', playing);
      b.setAttribute('aria-label', playing ? U.pause : U.listen);
      b.title = playing ? U.pause : U.listen;
      var t = b.querySelector('.t'); if (t) t.textContent = playing ? U.pause : U.listen;
    }
    function tick() {
      raf = 0;
      if (!playing || !recState) return;
      var t = audio.currentTime * 1000, st = recState;
      if (st.kind === 'ayah' && st.phase === 'ayah' && st.words) {
        var w = 0;
        for (var i = 0; i < st.words.length; i++) if (st.words[i][1] <= t) w = st.words[i][0]; else break;
        setHl({ s: st.s, a: st.a, w: w });
      } else if (st.kind === 'surah' && st.times) {
        var cur2 = null;
        for (var j = 0; j < st.times.length; j++) if (st.times[j][1] <= t) cur2 = st.times[j]; else break;
        if (cur2 && cur2[0] !== st.a) {
          st.a = cur2[0];
          ensureVisible(st.s, st.a);
        }
        if (cur2) setHl({ s: st.s, a: st.a, w: 0 });
      }
      raf = requestAnimationFrame(tick);
    }
    function startTick() { if (!raf) raf = requestAnimationFrame(tick); }
    function playSrc(url, muted) {
      audio.muted = !!muted;
      if (audio.getAttribute('src') !== url) audio.src = url;
      var pr = audio.play();
      if (pr && pr.catch) pr.catch(function () { stopAudio(); });
      startTick();
    }
    // Ayah-by-ayah reciters: basmala first when a surah starts (not Al-Fatiha, which begins with it, nor At-Tawbah).
    // The per-ayah English files were cut from a recording where the Arabic recitation came first, so some begin
    // with the end of the reciter's voice (an echo, sometimes a letter). Find where the English starts from the first
    // ~2.5 s of the file (fetched and decoded ahead of time) and start playback there (#t= media fragment).
    var leadCache = {}, decoder = null;
    function leadOffset(url) {
      if (leadCache[url]) return leadCache[url];
      var p = new Promise(function (res) {
        var Ctx = window.OfflineAudioContext || window.webkitOfflineAudioContext;
        if (!Ctx || !window.fetch) return res(0);
        var done = false, fin = function (v) { if (!done) { done = true; res(v); } };
        setTimeout(function () { fin(0); }, 4000);
        fetch(url, { headers: { Range: 'bytes=0-59999' } }).then(function (r) { return r.arrayBuffer(); }).then(function (buf) {
          if (!decoder) decoder = new Ctx(1, 1, 44100);
          return new Promise(function (ok, bad) { var q2 = decoder.decodeAudioData(buf, ok, bad); if (q2 && q2.then) q2.then(ok, bad); });
        }).then(function (a) {
          var d = a.getChannelData(0), w = Math.round(a.sampleRate * 0.05), env = [];
          for (var i = 0; i + w <= d.length; i += w) { var sum = 0; for (var j = i; j < i + w; j += 4) sum += d[j] * d[j]; env.push(Math.sqrt(sum / (w / 4)) * 1000); }
          var loud = function (k) { return env[k] >= 20; }, quiet = function (k, n) { for (var m = k; m < k + n; m++) if (m >= env.length || env[m] >= 10) return false; return true; };
          var i0 = 0; while (i0 < env.length && !loud(i0)) i0++;
          if (i0 >= env.length) return fin(0);
          var j0 = i0; while (j0 < env.length && !quiet(j0, 4)) j0++;
          var start = i0;
          if (i0 * 50 < 1500 && (j0 - i0) * 50 <= 300) {       // a short burst then silence: the reciter's last letter
            var k0 = j0; while (k0 < env.length && !loud(k0)) k0++;
            if (k0 < env.length) start = k0;
          }
          fin(Math.max(0, start * 50 - 80) / 1000);
        }).catch(function () { fin(0); });
      });
      p.then(function (v) { p.v = v; });
      leadCache[url] = p;
      return p;
    }
    function meaningUrl(r, s, a) { return (r.then || r.url).replace('{s}', pad(s)).replace('{a}', pad(a)); }
    function playTrimmed(url) {
      var p = leadOffset(url);
      if (p.v !== undefined) return playSrc(p.v > 0.05 ? url + '#t=' + p.v.toFixed(2) : url);
      // not analysed yet (e.g. the very first tap): start at once but muted — phones only allow playing right
      // after a tap — then jump past the reciter's tail and unmute.
      playSrc(url, true);
      p.then(function (off) {
        if (audio.getAttribute('src') === url && off > 0.05 && audio.currentTime < off) { try { audio.currentTime = off; } catch (e) {} }
        audio.muted = false;
      });
    }

    // r.then: after the ayah, play its meaning (one file per ayah) with the whole ayah highlighted.
    function playMeaning(s, a) {
      var r = rec();
      recState = { kind: 'ayah', s: s, a: a, words: null, phase: 'meaning' };
      setHl({ s: s, a: a, w: 0 });
      if (r.trimLead) {
        playTrimmed(meaningUrl(r, s, a));
        var n = nextAyah(s, a); if (n) leadOffset(meaningUrl(r, n[0], n[1]));   // analyse the next one ahead
      } else playSrc(meaningUrl(r, s, a));
    }
    function playAyah(s, a, skipBasmala) {
      var r = rec();
      recState = { kind: 'ayah', s: s, a: a, words: null, phase: 'ayah' };
      var go1 = function () {
        if (!playing) return;
        if (a === 1 && s !== 1 && s !== 9 && !skipBasmala) {
          recState.phase = 'basmala';
          setHl({ basmala: true });
          if (r.trimLead) playTrimmed(srcOf(r, 1, 1)); else playSrc(srcOf(r, 1, 1));
        } else {
          setHl({ s: s, a: a, w: 0 });
          if (r.trimLead) {
            playTrimmed(srcOf(r, s, a));
            var n = nextAyah(s, a); if (n) leadOffset(srcOf(r, n[0], n[1]));
          } else {
            playSrc(srcOf(r, s, a));
            if (r.then && r.trimLead) leadOffset(meaningUrl(r, s, a));      // prepare the meaning while the ayah is recited
          }
        }
        if (r.timed) wordTimes(r, s, a).then(function (w) { if (recState && recState.s === s && recState.a === a) recState.words = w; }, function () {});
      };
      if (visible().indexOf(pageOf(s, a)) >= 0) go1();          // same page: start at once (keeps the tap's permission to play)
      else ensureVisible(s, a).then(go1);
    }
    function playSurah(s, a) {
      var r = rec(), url = srcOf(r, s);
      recState = { kind: 'surah', s: s, a: a, times: null };
      ensureVisible(s, a);
      playSrc(url);
      if (!r.timed) { setHl(null); return; }
      ayahTimes(r, s).then(function (times) {
        if (!recState || recState.s !== s) return;
        recState.times = times;
        var start = times.filter(function (x) { return x[0] === a; })[0];
        if (start && a > 1) {
          var seek = function () { try { audio.currentTime = start[1] / 1000; } catch (e) {} };
          if (audio.readyState >= 1) seek(); else audio.addEventListener('loadedmetadata', seek, { once: true });
        }
      }, function () {});
    }
    function onEnded() {
      if (!playing || !recState) return;
      var st = recState;
      if (st.kind === 'ayah') {
        if (st.phase === 'basmala') return playAyah(st.s, st.a, true);
        if (st.phase === 'ayah' && rec().then) return playMeaning(st.s, st.a);
        var n = nextAyah(st.s, st.a);
        if (n) playAyah(n[0], n[1]); else stopAudio();
      } else {
        if (st.s < 114) playSurah(st.s + 1, 1); else stopAudio();
      }
    }
    function startAudio() {
      if (!RECS.length) return;
      if (!audio) {
        audio = new Audio(); audio.preload = 'auto';
        audio.addEventListener('ended', onEnded);
        audio.addEventListener('error', function () { if (playing) { stopAudio(); } });
      }
      playing = true; setPlayUI();
      var r = rec(), first = MAP.pages[cur - 1];
      // meaning only: on a phone showing one page, show the meaning page (the English text is what is being read)
      if (r.meaningOnly && narrow() && book.dataset.show !== 'tr') { var tb = root.querySelector('.bk-tab[data-show="tr"]'); if (tb) tb.click(); }
      // resume where it paused if that ayah is still on screen; otherwise start at the top of the page
      if (recState && lastRec === r.id && visible().indexOf(pageOf(recState.s, recState.a)) >= 0 && audio.currentTime > 0 && !audio.ended) {
        audio.play(); startTick(); return;
      }
      if (r.kind === 'ayah') playAyah(first[0], first[1]);
      else playSurah(first[0], first[1]);
      lastRec = r.id;
    }
    function stopAudio() {
      if (!playing) return;
      playing = false;
      if (audio) audio.pause();
      if (raf) { cancelAnimationFrame(raf); raf = 0; }
      setPlayUI();
    }
    function setupAudio() {
      var b = q('play'), sel = q('reciter');
      if (!b || !sel || !RECS.length) { var box = root.querySelector('.bk-audio'); if (box) box.hidden = true; return; }
      var saved = embed ? null : load('lt_book_rec');
      recId = RECS.some(function (r) { return r.id === saved; }) ? saved : RECS[0].id;
      sel.innerHTML = RECS.map(function (r) { return '<option value="' + r.id + '">' + esc(r.label) + '</option>'; }).join('');
      sel.value = recId;
      sel.onchange = function () {
        recId = sel.value; if (!embed) store('lt_book_rec', recId);
        var was = playing; stopAudio(); recState = null; setHl(null);
        if (was) startAudio();
      };
      b.onclick = function () { if (playing) stopAudio(); else startAudio(); };
    }

    // Reader's choice of page frame (a preference, kept for every book on the site):
    // 'sides' = ornament on three sides, the spine side marked (default); 'full' = ornament all round; 'none' = plain.
