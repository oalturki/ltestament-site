      // offsetWidth, not getBoundingClientRect: the page may be mid-turn (rotated), and layout widths ignore transforms.
      box.querySelectorAll('.ml:not(.ml-s):not(.ml-b)').forEach(function (l) { maxW = Math.max(maxW, l.offsetWidth); });
